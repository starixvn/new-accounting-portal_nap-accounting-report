namespace Fanex.AccountingReports.Misc.Services.Implement.AutoGeneratedReport
{
    using System;
    using System.Collections.Generic;
    using System.IO;
    using System.Linq;
    using System.Net;
    using Fanex.AccountingReports.Core.Configurations;
    using Fanex.AccountingReports.Core.Services.Impl;
    using Fanex.AccountingReports.Misc.Models.AutoGeneratedReport;
    using Fanex.AccountingReports.Misc.Services.Interface.AutoGeneratedReport;
    using Fanex.Common;
    using Fanex.ServiceManagement.Utility;

    public class AutoGeneratedHistoryReport : IAutoGeneratedHistoryReport
    {
        private string _ip = AppSettings.IP;
        private string _password = AppSettings.Password;
        private string _username = AppSettings.UserName;

        private NetworkCredential _networkCredential;

        private List<ReportGroup> _historyReports = null;

        public AutoGeneratedHistoryReport()
        {
            _historyReports = new List<ReportGroup>();

            if (AppSettings.IsAuthenticate)
            {
                if (AppSettings.IsEncryptPassword)
                {
                    _password = Cryptography.CfsDeCrypt(_password);
                }

                _networkCredential = new NetworkCredential(_username, _password);
            }
        }

        public List<ReportGroup> GetHistoryReports(string folderName, string parentFunctionKey)
        {
            if (AppSettings.IsAuthenticate)
            {
                using (new NetworkConnection(@"\\" + _ip, _networkCredential))
                {
                    GetReportsByUser(folderName, parentFunctionKey);
                }
            }
            else
            {
                GetReportsByUser(folderName, parentFunctionKey);
            }

            return _historyReports.OrderByDescending(s => Converter.To<DateTime>(s.GroupName)).ToList();                
        }

        private void GetReportsByUser(string folderName, string parentFunctionKey)
        {
            string currentReportParentFolder = Path.Combine(AppSettings.AutoGenerateReportParentFolder, folderName);

            if (File.Exists(currentReportParentFolder))
            {
                if (parentFunctionKey == "Others")
                {
                    ProcessFileForGroupByDay(folderName, currentReportParentFolder);
                }
                else
                {
                    ProcessFile(folderName, currentReportParentFolder);
                }
            }
            else if (Directory.Exists(currentReportParentFolder))
            {
                ProcessDirectory(folderName, currentReportParentFolder, parentFunctionKey);
            }            
        }

        private void ProcessDirectory(string functionKey, string directory, string parentFunctionKey)
        {
            string[] files = Directory.GetFiles(directory);
            foreach (string file in files)
            {
                if (parentFunctionKey == "Others")
                {
                    ProcessFileForGroupByDay(functionKey, file);
                }
                else
                {
                    ProcessFile(functionKey, file);
                }
            }

            string[] subDirectories = Directory.GetDirectories(directory);
            foreach (var subDirectory in subDirectories)
            {
                ProcessDirectory(functionKey, subDirectory, parentFunctionKey);
            }
        }

        private void ProcessFile(string functionKey, string reportPath)
        {
            bool hasPermission = PermissionService.HasReadPermission(functionKey);
            if (!hasPermission)
            {
                return;
            }

            DateTime latestModifyDate = File.GetLastWriteTime(reportPath);
            string groupName = latestModifyDate.ToString("MMM - yyyy");
            string subGroupName = latestModifyDate.ToString("MMM - dd - yyyy");

            if (latestModifyDate.Date >= DateTime.Today.AddMonths(-12).Date)
            {
                var report = new Report()
                {
                    Name = Path.GetFileName(reportPath),                    
                    FolderName = reportPath.Replace(string.Format("{0}\\", AppSettings.AutoGenerateReportParentFolder), string.Empty),
                    GeneratedDate = latestModifyDate.ToString("yyyy-MM-dd"),
                    GeneratedDateFull = latestModifyDate,
                    FunctionKey = functionKey
                };

                ReportGroup group = _historyReports.Where(s => s.GroupName == groupName).Distinct().FirstOrDefault();

                if (group == null)
                {
                    group = new ReportGroup();
                    group.GroupName = groupName;

                    _historyReports.Add(group);
                }

                group.Reports.Add(report);
                group.Reports = group.Reports.OrderByDescending(s => s.GeneratedDateFull).ToList();
            }
        }

        private void ProcessFileForGroupByDay(string functionKey, string reportPath)
        {
            bool hasPermission = PermissionService.HasReadPermission(functionKey);
            if (!hasPermission)
            {
                return;
            }

            DateTime latestModifyDate = File.GetLastWriteTime(reportPath);
            string groupName = latestModifyDate.ToString("MMM - yyyy");
            string subGroupName = latestModifyDate.ToString("MMM - dd - yyyy");

            if (latestModifyDate.Date >= DateTime.Today.AddMonths(-12).Date)
            {
                var report = new Report()
                {
                    Name = Path.GetFileName(reportPath),                    
                    FolderName = reportPath.Replace(string.Format("{0}\\", AppSettings.AutoGenerateReportParentFolder), string.Empty),
                    GeneratedDate = latestModifyDate.ToString("yyyy-MM-dd"),
                    GeneratedDateFull = latestModifyDate,
                    FunctionKey = functionKey
                };

                ReportGroup group = _historyReports.Where(s => s.GroupName == groupName).Distinct().FirstOrDefault();                

                if (group == null)
                {
                    group = new ReportGroup();
                    group.GroupName = groupName;
                    
                    _historyReports.Add(group);
                }

                var subGroup = group.Rows.Where(s => s.GroupName == subGroupName).Distinct().FirstOrDefault();
                if (subGroup == null)
                {
                    subGroup = new ReportGroup();
                    subGroup.GroupName = subGroupName;                    
                    group.Rows.Add(subGroup);                
                }

                subGroup.Reports.Add(report);

                subGroup.Reports = subGroup.Reports.OrderByDescending(s => s.GeneratedDateFull).ToList();
                group.Rows = group.Rows.OrderByDescending(s => Converter.To<DateTime>(s.GroupName)).ToList();
            }
        }
    }
}
