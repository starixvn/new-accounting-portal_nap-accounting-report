namespace Fanex.AccountingReports.Misc.Services.Implement.AutoGeneratedReport
{
	using Core.Web;
	using Fanex.AccountingReports.Misc.Models.AutoGeneratedReport;
	using Fanex.NAP.Core.Configuration;
	using NAP.Core.Business;
	using NAP.Core.Service.Impl;
	using System.Collections.Generic;
	using System.Data;
	using System.Linq;

	public class AutoGeneratedTodayReport
    {
	    public List<ReportFunction> GetAllReportFunctions(int userId)
        {
            var result = new List<ReportFunction>();
            var userService = new UserService();
            var parentFunctions = userService.GetPermissions(userId, NapSettings.Settings.SiteId, AccReportFunctionKeys.AutoGeneratedReport, NapSettings.Settings.Environment)
                                    .Where(p => p.Policy >= (int)Constant.Policy.Read);
            foreach (var parentFunction in parentFunctions)
            {
                var functions = userService.GetPermissions(userId, NapSettings.Settings.SiteId, parentFunction.Key, NapSettings.Settings.Environment)
                                    .Where(p => p.Policy >= (int)Constant.Policy.Read);
                var reportFunctions = functions.Select(f => new ReportFunction
                {
                    FunctionKey = f.Key,
                    FunctionName = f.Name,
                    ParentFunctionKey = parentFunction.Key,
                    Description = f.Description
                });

                result.AddRange(reportFunctions);
            }

            return result.OrderBy(f => f.FunctionName).ToList();
        }
    }
}