namespace Fanex.AccountingReports.Misc.Services.Implement.AutoGeneratedReport
{
    using System;
    using System.Collections.Generic;
    using System.Data;
    using System.IO;
    using System.Linq;
    using System.Net;
    using Core.Web;
    using Fanex.AccountingReports.Core.Configurations;
    using Fanex.AccountingReports.Misc.Models.AutoGeneratedReport;
    using Fanex.Common;
    using Fanex.NAP.Core.Configuration;
    using Fanex.ServiceManagement.Utility;
    using NAP.Core.Business;
    using NAP.Core.Service.Impl;

    public class AutoGeneratedTodayReport
    {
        private string _ip = AppSettings.IP;
        private string _password = AppSettings.Password;
        private string _username = AppSettings.UserName;

        private NetworkCredential _networkCredential;

        private List<ReportGroup> _reportList = null;
        private List<ReportGroup> _todayReports = null;

        public AutoGeneratedTodayReport()
        {
            _reportList = new List<ReportGroup>();

            if (AppSettings.IsAuthenticate)
            {
                if (AppSettings.IsEncryptPassword)
                {
                    _password = Cryptography.CfsDeCrypt(_password);
                }

                _networkCredential = new NetworkCredential(_username, _password);
            }
        }

        public List<ReportFunction> GetAllReportFunctions(int userId)
        {
            var result = new List<ReportFunction>();
            var userService = new UserService();
            var parentFunctions = userService.GetPermissions(userId, NapSettings.Settings.SiteId, AccReportFunctionKeys.AutoGeneratedReport, NapSettings.Settings.Environment)
                                    .Where(p => p.Policy >= (int)Constant.Policy.Read);
            foreach (var parentFunction in parentFunctions)
            {
                var functions = userService.GetPermissions(userId, NapSettings.Settings.SiteId, parentFunction.Key, NapSettings.Settings.Environment)
                                    .Where(p => p.Policy >= (int)Constant.Policy.Read);
                var reportFunctions = functions.Select(f => new ReportFunction
                {
                    FunctionKey = f.Key,
                    FunctionName = f.Name,
                    ParentFunctionKey = parentFunction.Key,
                    Description = f.Description
                });

                result.AddRange(reportFunctions);
            }

            return result.OrderBy(f => f.FunctionName).ToList();
        }

        public List<ReportGroup> GetTodayReports(int userId)
        {
            var reportsByUser = GetAllReportFunctions(userId);

            if (AppSettings.IsAuthenticate)
            {
                using (new NetworkConnection(@"\\" + _ip, _networkCredential))
                {
                    return GetTodayReportsByUser(reportsByUser);
                }
            }
            else
            {
                return GetTodayReportsByUser(reportsByUser);
            }
        }

        public List<ReportGroup> GetTodayReportsByUser(List<ReportFunction> reportsByUser)
        {
            _todayReports = new List<ReportGroup>();

            foreach (var reportItem in reportsByUser)
            {
                string currentReportParentFolder = Path.Combine(AppSettings.AutoGenerateReportParentFolder, reportItem.FunctionKey);

                if (File.Exists(currentReportParentFolder))
                {
                    ProcessFile(reportItem.FunctionKey, reportItem.Description, currentReportParentFolder);
                }
                else if (Directory.Exists(currentReportParentFolder))
                {
                    ProcessDirectory(reportItem.FunctionKey, reportItem.Description, currentReportParentFolder);
                }
            }

            return _todayReports.OrderBy(p => p.GroupName).ToList();
        }

        private void ProcessDirectory(string functionKey, string reportDescription, string directory)
        {
            string[] files = Directory.GetFiles(directory);
            foreach (string file in files)
            {
                ProcessFile(functionKey, reportDescription, file);
            }

            string[] subDirectories = Directory.GetDirectories(directory);
            foreach (var subDirectory in subDirectories)
            {
                ProcessDirectory(functionKey, reportDescription, subDirectory);
            }
        }

        private void ProcessFile(string functionKey, string reportDescription, string reportPath)
        {
            var latestModifyDate = File.GetLastWriteTime(reportPath);
            if (latestModifyDate.Date == DateTime.Today.Date)
            {
                var report = new Report()
                {
                    Name = Path.GetFileName(reportPath),
                    Description = reportDescription,
                    FolderName = reportPath.Replace(string.Format("{0}\\", AppSettings.AutoGenerateReportParentFolder), string.Empty),
                    GeneratedDate = latestModifyDate.ToString("yyyy-MM-dd"),
                    GeneratedDateFull = latestModifyDate,
                    FunctionKey = functionKey
                };

                ReportGroup group = _todayReports.Where(s => s.GroupName == reportDescription).Distinct().FirstOrDefault();
                if (group == null)
                {
                    group = new ReportGroup();
                    group.GroupName = reportDescription;

                    _todayReports.Add(group);
                }

                group.Reports.Add(report);
                group.Reports = group.Reports.OrderByDescending(s => s.GeneratedDateFull).ToList();
            }
        }
    }
}