using Fanex.Data;
using Fanex.Data.Repository;

namespace Fanex.AccountingReports.Misc.Repositories
{
    public class AutoGeneratedReportRepository
    {
        public void WriteUserLog(ICriteria criteria)
        {
            using (var db = new ObjectDb(criteria.GetSettingKey()))
            {
                db.ExecuteNonQuery(criteria.GetSpParams());
            }
        }
    }
}
