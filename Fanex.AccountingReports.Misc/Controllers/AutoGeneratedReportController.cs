namespace Fanex.AccountingReports.Misc.Controllers
{
    using System;
    using System.IO;
    using System.Net;
    using System.Web.Mvc;
    using Fanex.AccountingReports.Core.Configurations;
    using Fanex.AccountingReports.Core.Services.Impl;
    using Fanex.AccountingReports.Core.Web;
    using Fanex.AccountingReports.Core.Web.Controllers;
    using Fanex.AccountingReports.Misc.Models.AutoGeneratedReport;
    using Fanex.AccountingReports.Misc.Services.Implement.AutoGeneratedReport;
    using Fanex.Common;
    using Fanex.NAP.Core.Business;
    using Fanex.NAP.Core.Web.Attribute;
    using Fanex.ServiceManagement.Utility;
    using Ionic.Zip;

    /// <summary>
    /// TODO: Update summary.
    /// </summary>
    public class AutoGeneratedReportController : BaseController
    {
        private readonly AutoGeneratedTodayReport _autoGeneratedTodayReport = null;
        private readonly AutoGeneratedHistoryReport _autoGeneratedHistoryReport = null;
        private readonly string _ip = AppSettings.IP;
        private readonly string _password = AppSettings.Password;
        private readonly string _username = AppSettings.UserName;

        private readonly NetworkCredential _networkCredential;

        public AutoGeneratedReportController()
        {
            _autoGeneratedTodayReport = new AutoGeneratedTodayReport();
            _autoGeneratedHistoryReport = new AutoGeneratedHistoryReport();
            if (AppSettings.IsAuthenticate)
            {
                if (AppSettings.IsEncryptPassword)
                {
                    _password = Cryptography.CfsDeCrypt(_password);
                }

                _networkCredential = new NetworkCredential(_username, _password);
            }
        }

        [HttpGet]
        [UserActivityFilter]
        [NapAuth(FunctionKey = AccReportFunctionKeys.AutoGeneratedReport, Policy = Constant.Policy.Read)]
        public ActionResult Index()
        {
            return View("~/Areas/Misc/Views/AutoGeneratedReport/Index.cshtml");
        }

        [HttpPost]
        public JsonResult GetReports()
        {
            var report = _autoGeneratedTodayReport.GetAllReportFunctions(CurrentSession.UserId);
            return Json(report);
        }

        [HttpPost]
        public JsonResult GetTodayReports()
        {
            var report = _autoGeneratedTodayReport.GetTodayReports(CurrentSession.UserId);
            return Json(report);
        }

        [HttpPost]
        public JsonResult GetHistoryReports(string folderName, string parentFunctionKey)
        {
            var report = _autoGeneratedHistoryReport.GetHistoryReports(folderName, parentFunctionKey);
            return Json(report);
        }

        public ActionResult DownLoadReport(DownloadReportCriteria criteria)
        {
            var fileNames = criteria.FileName.Split('^');
            var isMultiFiles = criteria.IsMultiFiles;

            if (AppSettings.IsAuthenticate)
            {
                using (new NetworkConnection(@"\\" + _ip, _networkCredential))
                {
                    return DownLoadExcelFiles(fileNames, isMultiFiles);
                }
            }
            else
            {
                return DownLoadExcelFiles(fileNames, isMultiFiles);
            }
        }

        private FileContentResult DownLoadExcelFiles(string[] fileNames, bool isMultiFiles)
        {
            if (isMultiFiles)
            {
                return GetMultiFiles(fileNames);
            }
            else
            {
                return GetSingleFile(fileNames[0]);
            }
        }

        private FileContentResult GetSingleFile(string file)
        {
            string groupName = file.Split('|')[0];
            string fileNameAndFunctionKey = file.Split('|')[1];
            string[] array = fileNameAndFunctionKey.Split('#');
            string fileName = array[0];
            string functionKey = array[1];

            bool hasPermission = PermissionService.HasReadPermission(functionKey);
            if (!hasPermission)
            {
                return null;
            }

            return GetFile(fileName);
        }

        private FileContentResult GetMultiFiles(string[] fileNames)
        {
            string fileZipName = "Auto-Generated Report - " + AppSession.CurrentUser.Username + " - " + DateTime.Now.ToString("yyyy-MM-dd hh-mm tt") + ".zip";
            string reportZipFolderPath = Path.Combine(AppSettings.AutoGenerateReportParentFolder, fileZipName);

            bool hasAnyFile = false;
            using (ZipFile zip = new ZipFile())
            {
                foreach (string file in fileNames)
                {
                    string groupName = file.Split('|')[0];
                    string fileNameAndFunctionKey = file.Split('|')[1];
                    string[] array = fileNameAndFunctionKey.Split('#');
                    string fileName = array[0];
                    string functionKey = array[1];

                    bool hasPermission = PermissionService.HasReadPermission(functionKey);
                    if (!hasPermission)
                    {
                        continue;
                    }

                    string path = Path.Combine(AppSettings.AutoGenerateReportParentFolder, fileName);
                    DateTime latestModifyDate = System.IO.File.GetLastWriteTime(path);
                    zip.AddFile(path, groupName);
                    hasAnyFile = true;
                }

                zip.Save(reportZipFolderPath);
            }

            if (!hasAnyFile)
            {
                return null;
            }

            var excelFiles = GetFile(fileZipName);
            System.IO.File.Delete(reportZipFolderPath);

            return excelFiles;
        }

        private FileContentResult GetFile(string fileName)
        {
            string filePath = Path.Combine(AppSettings.AutoGenerateReportParentFolder, fileName);
            byte[] fileBytes = System.IO.File.ReadAllBytes(filePath);
            string fileExtension = Path.GetExtension(filePath);
            var mimeType = GetMimeType(fileExtension);

            string shortFileName = System.IO.Path.GetFileName(filePath);
            var contentResult = File(fileBytes, mimeType, shortFileName);
            return contentResult;
        }

        private string GetMimeType(string fileExtension)
        {
            if (fileExtension.StartsWith("."))
            {
                fileExtension = fileExtension.Substring(1);
            }

            switch (fileExtension.ToLower())
            {
                case "xls":
                    return "application/vnd.ms-excel";

                case "xlsx":
                    return "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet";

                case "doc":
                    return "application/msword";

                case "zip":
                    return "application/x-zip-compressed";

                case "pdf":
                    return "application/pdf";

                default:
                    return System.Net.Mime.MediaTypeNames.Application.Octet;
            }
        }
    }
}